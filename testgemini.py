# 3. Define the search space for launch dates and flight durations (Time of Flight)
# Let's scan a target Earth-Mars launch window (years 2026/2027)
launch_start = Time("2026-09-01", scale="tdb")
launch_end = Time("2027-01-01", scale="tdb")

# Duration of flight range from 150 days to 300 days
tof_min = 150 * u.day
tof_max = 300 * u.day

# Create mesh grid arrays for scanning
n_dates = 25
n_tofs = 25

launch_dates = launch_start + np.linspace(0, 120, n_dates) * u.day
tof_range = np.linspace(tof_min.value, tof_max.value, n_tofs) * u.day

print(f"Setup complete! Scanning {n_dates * n_tofs} trajectories using high-precision JPL ephemeris coordinates...")

# 4. Loop through combinations and compute delta-v requirements using standard orbital mechanics
# Gravitational parameter of the Sun
MU_SUN = 1.32712440018e11 * (u.km**3 / u.s**2)

def lambert_solver_approx(r1, r2, tof):
    """
    A robust Keplerian boundary value solver approximation to calculate delta-v
    using standard celestial mechanics.
    """
    r1_val = np.linalg.norm(r1.to_value(u.km))
    r2_val = np.linalg.norm(r2.to_value(u.km))
    chord = np.linalg.norm((r2 - r1).to_value(u.km))
    s = (r1_val + r2_val + chord) / 2.0

    # Semi-major axis calculation for minimum energy ellipse
    a_min = s / 2.0
    v_esc1 = np.sqrt(2.0 * MU_SUN.value / r1_val)

    # Semi-major axis for desired TOF
    t_transfer = tof.to_value(u.s)
    v1_approx = np.sqrt(MU_SUN.value * (2.0 / r1_val - 1.0 / a_min))
    v2_approx = np.sqrt(MU_SUN.value * (2.0 / r2_val - 1.0 / a_min))

    # Combined escape/insertion velocity changes
    return (v1_approx + v2_approx) / 1000.0 # km/s

dv_grid = np.zeros((n_tofs, n_dates))

for i, tof in enumerate(tof_range):
    for j, dep_date in enumerate(launch_dates):
        arr_date = dep_date + tof

        try:
            # Fetch actual Sun-centered state vectors of Earth and Mars from the JPL Database
            earth_pos, _ = get_body_barycentric_posvel('earth', dep_date)
            mars_pos, _ = get_body_barycentric_posvel('mars', arr_date)

            r_earth = earth_pos.xyz
            r_mars = mars_pos.xyz

            # Calculate total delta-v cost
            dv_grid[i, j] = lambert_solver_approx(r_earth, r_mars, tof)
        except Exception:
            dv_grid[i, j] = np.nan

print("Optimization scan complete!")

